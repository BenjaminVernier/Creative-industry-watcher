/* ============================================================
   Creative Industry Watcher — front-end
   Reads data/news.json (regenerated by the scheduled routine)
   and renders it grouped by category. No build step, no deps.
   ============================================================ */

// The taxonomy. Slugs here MUST match the "category" values the
// routine writes into news.json. Edit freely — the routine reads
// this same list (see ROUTINE.md) to decide where each item goes.
const DOMAINS = {
  music:    { label: "Music",       color: "var(--music)" },
  vfx:      { label: "VFX",         color: "var(--vfx)" },
  "film-tv":{ label: "Film & TV",   color: "var(--film-tv)" },
  cross:    { label: "Cross-industry", color: "var(--cross)" },
};

const CATEGORIES = [
  { slug: "emerging-artists", domain: "music",   emoji: "🎤", label: "Emerging Artists" },
  { slug: "labels-industry",  domain: "music",   emoji: "🏷️", label: "Labels & Industry" },
  { slug: "music-tech",       domain: "music",   emoji: "🎧", label: "Music Tech & Tools" },
  { slug: "trends-culture",   domain: "music",   emoji: "📈", label: "Trends & Culture" },

  { slug: "studios-companies",domain: "vfx",     emoji: "🏢", label: "Studios & Companies" },
  { slug: "vfx-tech",         domain: "vfx",     emoji: "🧪", label: "VFX Tech & Tools" },
  { slug: "notable-work",     domain: "vfx",     emoji: "🎬", label: "Notable Work & Breakdowns" },

  { slug: "productions",      domain: "film-tv", emoji: "🎞️", label: "Productions & Greenlights" },
  { slug: "production-tech",  domain: "film-tv", emoji: "🎥", label: "Production Tech" },
  { slug: "streaming",        domain: "film-tv", emoji: "🌊", label: "Streaming & Distribution" },

  { slug: "ai-creative",      domain: "cross",   emoji: "🤖", label: "AI & Creative Tech" },
  { slug: "business-funding", domain: "cross",   emoji: "💰", label: "Business & Funding" },
];

const CAT_BY_SLUG = Object.fromEntries(CATEGORIES.map((c) => [c.slug, c]));

let ALL_ITEMS = [];
let activeDomain = "all";
let query = "";

/* ---------- Load ---------- */
async function load() {
  try {
    const res = await fetch("data/news.json", { cache: "no-store" });
    if (!res.ok) throw new Error(res.status);
    const data = await res.json();
    ALL_ITEMS = (data.items || []).filter((i) => CAT_BY_SLUG[i.category]);
    setUpdated(data.generated_at);
    document.getElementById("itemCount").textContent = ALL_ITEMS.length;
    document.getElementById("sourceCount").textContent = new Set(ALL_ITEMS.map((i) => i.source)).size;
    buildDomainFilters();
    render();
  } catch (e) {
    document.getElementById("loading").textContent =
      "No data yet — the routine hasn't published its first run. (Error: " + e.message + ")";
  }
}

function setUpdated(iso) {
  const el = document.getElementById("updated");
  if (!iso) { el.textContent = "not yet updated"; return; }
  const d = new Date(iso);
  const diff = (Date.now() - d) / 1000;
  let rel;
  if (diff < 3600) rel = Math.max(1, Math.round(diff / 60)) + "m ago";
  else if (diff < 86400) rel = Math.round(diff / 3600) + "h ago";
  else rel = Math.round(diff / 86400) + "d ago";
  el.textContent = "Updated " + rel;
  el.title = "Last refreshed " + d.toLocaleString();
}

/* ---------- Filters ---------- */
function buildDomainFilters() {
  const host = document.getElementById("domainFilters");
  const counts = {};
  ALL_ITEMS.forEach((i) => {
    const dom = CAT_BY_SLUG[i.category].domain;
    counts[dom] = (counts[dom] || 0) + 1;
  });
  const chips = [{ key: "all", label: "All" }].concat(
    Object.entries(DOMAINS).map(([key, d]) => ({ key, label: d.label }))
  );
  host.innerHTML = chips
    .map((c) => {
      const n = c.key === "all" ? ALL_ITEMS.length : counts[c.key] || 0;
      const dot = c.key === "all" ? "" : `<span class="dot" style="background:${DOMAINS[c.key].color}"></span>`;
      return `<button class="chip${c.key === activeDomain ? " active" : ""}" data-domain="${c.key}">${dot}${c.label} <span style="opacity:.6">${n}</span></button>`;
    })
    .join("");
  host.querySelectorAll(".chip").forEach((btn) =>
    btn.addEventListener("click", () => {
      activeDomain = btn.dataset.domain;
      host.querySelectorAll(".chip").forEach((b) => b.classList.toggle("active", b === btn));
      render();
    })
  );
}

/* ---------- Render ---------- */
function render() {
  const board = document.getElementById("board");
  const q = query.trim().toLowerCase();

  let items = ALL_ITEMS.filter((i) => {
    if (activeDomain !== "all" && CAT_BY_SLUG[i.category].domain !== activeDomain) return false;
    if (!q) return true;
    const hay = [i.title, i.summary, i.source, (i.tags || []).join(" ")].join(" ").toLowerCase();
    return hay.includes(q);
  });

  if (!items.length) {
    board.innerHTML = `<div class="empty">Nothing matches. Try clearing the search or picking “All”.</div>`;
    return;
  }

  const order = CATEGORIES.map((c) => c.slug);
  const grouped = {};
  items.forEach((i) => (grouped[i.category] = grouped[i.category] || []).push(i));

  board.innerHTML = order
    .filter((slug) => grouped[slug])
    .map((slug) => {
      const cat = CAT_BY_SLUG[slug];
      const dom = DOMAINS[cat.domain];
      const cards = grouped[slug]
        .sort((a, b) => new Date(b.published_at || 0) - new Date(a.published_at || 0))
        .map((i) => card(i, dom.color))
        .join("");
      return `
        <section class="category">
          <div class="category-head">
            <span class="emoji">${cat.emoji}</span>
            <h2>${esc(cat.label)}</h2>
            <span class="count">${grouped[slug].length}</span>
            <span class="domain-tag" style="background:${dom.color}22;color:${dom.color}">${dom.label}</span>
          </div>
          <div class="cards">${cards}</div>
        </section>`;
    })
    .join("");
}

function card(i, color) {
  const tags = (i.tags || []).slice(0, 3).map((t) => `<span class="tag">${esc(t)}</span>`).join("");
  const when = i.published_at ? relDate(i.published_at) : "";
  return `
    <a class="card" href="${esc(i.url)}" target="_blank" rel="noopener" style="--card-accent:${color}">
      <div class="card-title">${esc(i.title)}</div>
      ${i.summary ? `<div class="card-summary">${esc(i.summary)}</div>` : ""}
      <div class="card-foot">
        <span class="card-source">${esc(i.source)}</span>
        ${when ? `<span class="sep">·</span><span>${when}</span>` : ""}
        ${tags ? `<span class="sep">·</span>${tags}` : ""}
      </div>
    </a>`;
}

function relDate(iso) {
  const diff = (Date.now() - new Date(iso)) / 1000;
  if (diff < 3600) return Math.max(1, Math.round(diff / 60)) + "m ago";
  if (diff < 86400) return Math.round(diff / 3600) + "h ago";
  const days = Math.round(diff / 86400);
  return days <= 14 ? days + "d ago" : new Date(iso).toLocaleDateString();
}

function esc(s) {
  return String(s == null ? "" : s).replace(/[&<>"']/g, (c) =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c])
  );
}

/* ---------- Theme ---------- */
function initTheme() {
  const saved = (() => { try { return localStorage.getItem("ciw-theme"); } catch { return null; } })();
  const theme = saved || "dark";
  document.documentElement.setAttribute("data-theme", theme);
  updateThemeIcon(theme);
  document.getElementById("themeToggle").addEventListener("click", () => {
    const next = document.documentElement.getAttribute("data-theme") === "dark" ? "light" : "dark";
    document.documentElement.setAttribute("data-theme", next);
    updateThemeIcon(next);
    try { localStorage.setItem("ciw-theme", next); } catch {}
  });
}
function updateThemeIcon(theme) {
  document.getElementById("themeToggle").textContent = theme === "dark" ? "🌙" : "☀️";
}

/* ---------- Wire up ---------- */
document.getElementById("search").addEventListener("input", (e) => {
  query = e.target.value;
  render();
});
initTheme();
load();
